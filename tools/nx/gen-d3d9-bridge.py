"""Generate D3D9 forwarders and ABI checks for the engine facade."""
from pathlib import Path
import re
import sys

header = Path(sys.argv[1]).read_text()
out = Path(sys.argv[2])
structs = set(re.findall(r'}\s*(D3D\w+)\s*[,;]', header))
enums = set(re.findall(r'typedef enum .*?}\s*(\w+);', header, re.S))
classes = re.findall(r'class (\w+)(?:\s*:\s*public \w+)?\s*\{(.*?)\};', header, re.S)
lines = ['// Generated by tools/nx/gen-d3d9-bridge.py. Do not edit.']
macro_lines = ['// Save native values before loading the engine facade macros.']
for name, tail in re.findall(r'^#define (D3D\w+)([^\n]*)', header, re.M):
    macro_lines += [f'#ifdef {name}']
    if not tail.startswith('('):
        macro_lines += [f'constexpr uint32_t nx_native_{name} = uint32_t({name});', f'#define NX_COMPARE_{name}']
        lines += [f'#ifdef NX_COMPARE_{name}', f'static_assert(uint32_t({name}) == nx_native_{name});', '#endif']
    macro_lines += [f'#undef {name}', '#endif']
out.with_name('d3d9_macro_capture.inc').write_text('\n'.join(macro_lines)+'\n')
for name in sorted(enums):
    lines += [f'static_assert(sizeof({name}) == sizeof(::{name}));']
for body in re.findall(r'typedef enum [^{]+\{([^{}]*)\}', header, re.S):
    for entry in body.split(','):
        match = re.match(r'\s*(\w+)\s*=', entry)
        if match:
            name = match.group(1)
            # FORCE_DWORD differs between headers but only specifies enum size.
            if name.endswith('FORCE_DWORD'):
                continue
            lines += [f'static_assert(uint32_t({name}) == uint32_t(::{name}));']
for name in sorted(structs - enums):
    lines += [f'static_assert(sizeof({name}) == sizeof(::{name}));',
              f'static_assert(alignof({name}) == alignof(::{name}));']
    body = re.search(r'typedef struct [^\{]+\{([^{}]*)\}\s*' + name + r'\b', header, re.S).group(1)
    for field in body.split(';'):
        field = field.strip()
        if not field:
            continue
        for part in field.split(','):
            member = re.search(r'(\w+)\s*(?:\[[^]]+\])?$', part).group(1)
            lines += [f'static_assert(offsetof({name}, {member}) == offsetof(::{name}, {member}));']

method_count = 0
for cls, body in classes:
    if cls == 'IUnknown9Like':
        continue
    for ret, method, params in re.findall(r'(HRESULT|UINT|DWORD|void|HMONITOR)\s+(\w+)\((.*?)\);', body, re.S):
        params = ' '.join(params.split())
        native_args, pre, post = [], [], []
        output = None
        for param in params.split(',') if params else []:
            match = re.fullmatch(r'\s*(.*?)\s*([A-Za-z_]\w*)\s*', param)
            assert match, param
            typ, name = match.groups()
            typ = typ.strip()
            base = re.sub(r'\bconst\b|\*|\s', '', typ)
            if typ.endswith('**') and base.startswith('IDirect3D'):
                assert output is None, (cls, method)
                output = (base, name)
                pre += [f'::{base}* nativeResult = nullptr;']
                native_args += [f'{name} ? &nativeResult : nullptr']
            elif base.startswith('IDirect3D') and typ.endswith('*'):
                native_args += [f'unwrap<::{base}>({name})']
            elif base in enums:
                native_args += [f'static_cast<::{base}>({name})']
            elif base in structs or base in ('RECT','POINT'):
                const = 'const ' if typ.startswith('const ') else ''
                assert typ.endswith('*'), param
                native_args += [f'reinterpret_cast<{const}::{base}*>({name})']
            elif name == 'dirtyRegion':
                native_args += ['static_cast<const RGNDATA*>(dirtyRegion)']
            else:
                assert base in {'UINT','DWORD','BOOL','INT','HWND','HANDLE','RECT','POINT','float','void','D3DCOLOR'}, param
                native_args += [name]
        if method == 'CreateDevice':
            pre += ['if (pp) { pp->hDeviceWindow = reinterpret_cast<HWND>(nwindowGetDefault()); pp->Windowed = TRUE; }',
                    'focusWindow = reinterpret_cast<HWND>(nwindowGetDefault());',
                    '// Game streaming and rendering touch resources on different threads.',
                    'behaviorFlags |= D3DCREATE_MULTITHREADED;']
        if method == 'Reset':
            pre += ['releaseGpuQueries();']
        if method.startswith('Draw'):
            pre += ['++drawCalls;']
        if method == 'Present':
            pre += ['const uint64_t presentStart = armGetSystemTick();']
            post += ['onPresent(result, presentStart);']
        call = f'unwrap<::{cls}>(this)->{method}({", ".join(native_args)})'
        lines += [f'{ret} {cls}::{method}({params}) {{']
        lines += ['    ' + v for v in pre]
        if ret == 'void':
            lines += ['    ' + call + ';']
        elif ret == 'HRESULT':
            lines += ['    HRESULT result = ' + call + ';']
            if output:
                base, name = output
                lines += [f'    if ({name}) *{name} = nullptr;',
                          f'    if (SUCCEEDED(result) && nativeResult) result = wrap(nativeResult, {name});']
            if method == 'CreateDevice':
                post += ['if (SUCCEEDED(result) && device && *device) onDeviceCreated(unwrap<::IDirect3DDevice9>(*device), pp);']
            if method.startswith(('Create', 'Draw', 'Lock', 'Unlock', 'Update')) or method in ('Reset', 'Present', 'GetData'):
                post += [f'reportFailure("{cls}::{method}", result);']
            lines += ['    ' + v for v in post]
            lines += ['    return result;']
        else:
            lines += ['    return ' + (f'reinterpret_cast<HMONITOR>({call})' if ret == 'HMONITOR' else call) + ';']
        lines += ['}', '']
        method_count += 1
assert method_count >= 90, method_count
out.write_text('\n'.join(lines))
print(f'Generated {method_count} D3D9 forwarders with ABI checks')
